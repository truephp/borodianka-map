import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const html=fs.readFileSync('index.html','utf8');
const from=html.indexOf('function dtekReportIsStale(){');
const to=html.indexOf('const dtekHouseFields=',from);
assert.ok(from>0&&to>from);
const ctx={Date, dtekSourceFetchedAt:new Date().toISOString(),dtekSourceErrors:[]};
vm.createContext(ctx);
vm.runInContext(html.slice(from,to)+'\nthis.isStale=dtekReportIsStale;this.warning=dtekReportWarning;',ctx);
assert.equal(ctx.isStale(),false);
ctx.dtekSourceFetchedAt=new Date(Date.now()-2*86400000).toISOString();
assert.equal(ctx.isStale(),true);
assert.match(ctx.warning(),/Застарілі дані ДТЕК/);
ctx.dtekSourceFetchedAt=new Date().toISOString();
ctx.dtekSourceErrors=[{city:'смт Бородянка',street:'вул. Дорожна'}];
assert.match(ctx.warning(),/вул\. Дорожна/);
assert.match(html,/if\(dtekReportIsStale\(\)\)return \{kind:'unknown',reason:'stale_dtek_address_data'\}/);
console.log('Stale and partial DTEK data safeguards: OK');
